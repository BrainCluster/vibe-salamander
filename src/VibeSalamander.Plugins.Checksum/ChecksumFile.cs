using System.Text;

namespace VibeSalamander.Plugins.Checksum;

/// <summary>One line of a checksum file: a file name (relative to the checksum file) and its checksum.</summary>
public sealed record ChecksumLine(string FileName, string Hex);

/// <summary>
/// Checksum files as Open Salamander writes and reads them:
/// SFV ("name  crc32"), and md5sum-style "hash  name" / "hash *name" for MD5, SHA-1, SHA-256 and SHA-512.
/// Reading also accepts the BSD / OpenSSL form "MD5 (name) = hash". Lines starting with ';' or '#' are comments.
/// </summary>
public static class ChecksumFile
{
    public const string Header = "; Generated by Vibe Salamander, https://github.com/BrainCluster/vibe-salamander";

    /// <summary>Writes the lines; names use '/' in hash files (like md5sum) and '\' in SFV files.</summary>
    public static void Write(TextWriter writer, HashKind kind, IEnumerable<ChecksumLine> lines)
    {
        writer.Write(Header + "\n;\n");
        foreach (ChecksumLine line in lines)
        {
            string hex = line.Hex.ToLowerInvariant();
            if (kind == HashKind.Crc)
                writer.Write($"{line.FileName.Replace('/', '\\')}  {hex}\n");
            else
                writer.Write($"{hex}  {line.FileName.Replace('\\', '/')}\n"); // two spaces: md5sum's text mode
        }
    }

    /// <summary>The checksum file's text (UTF-8, or the system code page for old files).</summary>
    public static string ReadText(string path)
    {
        byte[] bytes = File.ReadAllBytes(path);
        try
        {
            return new UTF8Encoding(false, throwOnInvalidBytes: true).GetString(bytes).TrimStart('﻿');
        }
        catch (DecoderFallbackException)
        {
            Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
            return Encoding.GetEncoding(System.Globalization.CultureInfo.CurrentCulture.TextInfo.ANSICodePage).GetString(bytes);
        }
    }

    private static IEnumerable<string> ContentLines(string text) =>
        text.Split('\n').Select(l => l.TrimEnd('\r').TrimStart(' ', '\t')).Where(l => l.Length > 0 && l[0] != ';' && l[0] != '#');

    /// <summary>What kind of checksum file this is (every line must fit), or null when it is none.</summary>
    public static HashKind? Detect(string text)
    {
        var candidates = new HashSet<HashKind>(HashKinds.All);
        bool any = false;
        foreach (string line in ContentLines(text))
        {
            any = true;
            foreach (HashKind kind in HashKinds.All)
                if (candidates.Contains(kind) && !Fits(line, kind))
                    candidates.Remove(kind);
            if (candidates.Count == 0)
                return null;
        }
        if (!any)
            return null;
        foreach (HashKind kind in HashKinds.All) // SFV first, like Open Salamander
            if (candidates.Contains(kind))
                return kind;
        return null;
    }

    private static bool Fits(string line, HashKind kind)
    {
        int length = HashKinds.HexLength(kind);
        if (kind == HashKind.Crc)
        {
            string last = LastWord(line, '\0');
            return last.Length == length && IsHex(last);
        }
        string first = FirstWord(line, '\0');
        if (first.Length == length && IsHex(first))
            return true;
        // MD5 (apache.zip) = eb5ba72b4164d765a79a7e06cee4eead
        string id = FirstWord(line, '(');
        string lastHash = LastWord(line, '=');
        return string.Equals(id, HashKinds.Id(kind), StringComparison.OrdinalIgnoreCase) && lastHash.Length == length && IsHex(lastHash);
    }

    /// <summary>The lines with their file names and checksums ('/' in names becomes '\').</summary>
    public static List<ChecksumLine> Parse(string text, HashKind kind, string checksumFilePath)
    {
        var result = new List<ChecksumLine>();
        bool first = true;
        foreach (string line in ContentLines(text))
        {
            ChecksumLine parsed = ParseLine(line, kind);
            string name = parsed.FileName.Replace('/', '\\');
            if (name.Length == 0 && first)
            {
                // a single hash without a name: the file named like the checksum file without its extension
                string own = Path.GetFileName(checksumFilePath);
                if (string.Equals(Path.GetExtension(own), HashKinds.Extension(kind), StringComparison.OrdinalIgnoreCase))
                    name = Path.GetFileNameWithoutExtension(own);
            }
            if (name.Length == 0)
                throw new FormatException("A line has no file name.");
            result.Add(new ChecksumLine(name, parsed.Hex.ToLowerInvariant()));
            first = false;
        }
        return result;
    }

    internal static ChecksumLine ParseLine(string line, HashKind kind)
    {
        line = line.TrimEnd(' ', '\t');
        int length = HashKinds.HexLength(kind);
        if (kind == HashKind.Crc)
        {
            string crc = LastWord(line, '\0');
            return new ChecksumLine(line[..^crc.Length].TrimEnd(' ', '\t'), crc);
        }

        string id = FirstWord(line, '(');
        string firstWord = FirstWord(line, '\0');
        if (!(firstWord.Length == length && IsHex(firstWord)) && string.Equals(id, HashKinds.Id(kind), StringComparison.OrdinalIgnoreCase))
        {
            // MD5 (name) = hash, or OpenSSL's MD5(name)= hash
            string hash = LastWord(line, '=');
            string rest = line[..^hash.Length].TrimEnd(' ', '\t');
            if (rest.EndsWith('='))
                rest = rest[..^1].TrimEnd(' ', '\t');
            rest = rest[id.Length..].TrimStart(' ', '\t');
            if (rest.StartsWith('(') && rest.EndsWith(')'))
                rest = rest[1..^1]; // names may contain ')' themselves: only the outer pair goes
            return new ChecksumLine(rest, hash);
        }

        // hash  name  /  hash *name (binary mode)
        string name = line[firstWord.Length..].TrimStart(' ', '\t');
        if (name.StartsWith('*'))
            name = name[1..];
        return new ChecksumLine(name, firstWord);
    }

    /// <summary>The first word: up to a space, a tab or <paramref name="stop"/>.</summary>
    private static string FirstWord(string line, char stop)
    {
        int end = 0;
        while (end < line.Length && line[end] != ' ' && line[end] != '\t' && line[end] != stop)
            end++;
        return line[..end];
    }

    /// <summary>The last word: back to a space, a tab or <paramref name="stop"/>.</summary>
    private static string LastWord(string line, char stop)
    {
        string trimmed = line.TrimEnd(' ', '\t');
        int start = trimmed.Length;
        while (start > 0 && trimmed[start - 1] != ' ' && trimmed[start - 1] != '\t' && trimmed[start - 1] != stop)
            start--;
        return trimmed[start..];
    }

    private static bool IsHex(string s) => s.Length > 0 && s.All(Uri.IsHexDigit);
}
